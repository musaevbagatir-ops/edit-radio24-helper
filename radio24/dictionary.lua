function add(k, v, note, cat)      -- cat: veh | gun | tob | item | biz (нет = как раньше)
    local key = T(k)
    DICT[key] = { val = T(v), note = note and T(note) or nil, cat = cat }
    local n = 1 + select(2, key:gsub(' ', ''))
    if n > MAXW then MAXW = n end
end

