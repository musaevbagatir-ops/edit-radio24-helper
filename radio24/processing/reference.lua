lowCache = {}
function lowUtf(s)
    local c = lowCache[s]
    if not c then c = lo(u8:decode(s)); lowCache[s] = c end
    return c
end

---------------------------------------------------------------------
-- ОБУЧЕНИЕ ПО СПРАВОЧНИКУ ПРО (REF):
--   примеры "исходник -> итог" -> готовые варианты (refFind), названия -> список названий (refSeedNames),
--   похожие запомненные объявления без цены -> вариант из памяти (memSimilar)
---------------------------------------------------------------------
REFEX = {}
REF_SEED_VER = 'refseed-1'
REF_SKIP_NAMES = {}
for _, w in ipairs({ 'Ganton', 'Grove', 'Grove Street', 'Willowfield', 'Glen Park', 'Idlewood', 'El Corona', 'East Beach', 'Ballas', 'Vagos', 'Aztec', 'Rifa' }) do
    REF_SKIP_NAMES[w:lower()] = true             -- районы и банды - не названия, в кавычки не берём
end

local function refIsExample(secTitle, line)
    return line:find('^Пр%.%d+:') ~= nil or secTitle:find('Примеры', 1, true) ~= nil
end

-- пары "исходник -> итог" из примеров ПРО (в CP1251, как всё остальное)
function refBuild()
    REFEX = {}
    pcall(function()
        for _, sec in ipairs(REF) do
            for _, line in ipairs(sec[2]) do
                if refIsExample(sec[1], line) then
                    local src, out = line:match('^Пр%.%d+:%s*(.-)%s*%->%s*(.+)$')
                    if not src then src, out = line:match('^(.-)%s*%->%s*(.+)$') end
                    if src and out and not out:find('%d%)') and not out:find('проверь', 1, true)
                        and not out:find('так в ПРО', 1, true) then
                        local s, o = u8:decode(src), u8:decode(out)
                        local k = norm(s)
                        if k ~= '' then
                            local sg = sigOf(s)
                            if k:find('%d') or sg == '' then sg = nil end   -- с цифрами только точное совпадение
                            REFEX[#REFEX + 1] = { src = s, out = (trim(o)), key = k, sg = sg, sec = u8:decode(sec[1]) }
                        end
                    end
                end
            end
        end
    end)
end

-- точное совпадение (true) или то же по сути объявление без цифр (false)
function refFind(ad)
    if not REFEX or #REFEX == 0 then return nil end
    local k = norm(ad)
    if k == '' then return nil end
    for _, ex in ipairs(REFEX) do
        if ex.key == k then return ex, true end
    end
    if k:find('%d') then return nil end
    local sg = sigOf(ad)
    if sg == '' then return nil end
    for _, ex in ipairs(REFEX) do
        if ex.sg == sg then return ex, false end
    end
    return nil
end

-- похожее запомненное объявление: та же суть, цифр (цен, номеров) нет ни в новом, ни в запомненном
function memSimilar(ad)
    if norm(ad):find('%d') then return nil end
    local sg = sigOf(ad)
    if sg == '' then return nil end
    local best
    for k, e in pairs(MEM) do
        if e._sg == nil then
            e._sg = false
            if not norm(e.orig):find('%d') then
                local s = sigOf(e.orig)
                if s ~= '' then e._sg = s end
            end
        end
        if e._sg == sg and (not best or (e.time or 0) > (best.time or 0)) then best = e end
    end
    return best and best.final or nil
end

-- Названия в кавычках из справочника, запомненных объявлений и эталонов -> список названий (один раз на версию)
local function refScanNames(txt, take)
    txt = stripColors(txt or '')
    local pos = 1
    while true do
        local a, b, nm = txt:find('"([^"]+)"', pos)
        if not a then break end
        pos = b + 1
        take(nm, txt:sub(1, a - 1))
    end
end

function refSeedNames()
    pcall(function()
        local flag = cfgPath('radio24_refseed.txt')
        local f = io.open(flag, 'rb')
        if f then
            local v = f:read('*a'); f:close()
            if v == REF_SEED_VER then return end
        end
        local added = 0
        local function take(nm, before)
            nm = trim(nm or '')
            if nm == '' or REF_SKIP_NAMES[lo(nm)] then return end
            if nm:find('^[A-Z0-9%-]+$') or (nm:find('%d') and #nm <= 6) then return end   -- номера, форматы, "38"
            local k = lo(nm)
            if NAMES[k] then return end
            if namesCheck(nm) then
                NAMES[k] = { cat = namesCat(before or ''), name = nm, n = 1, on = true }
                added = added + 1
            end
        end
        for _, sec in ipairs(REF) do
            for _, line in ipairs(sec[2]) do
                if refIsExample(sec[1], line) then
                    local out = line:match('%->%s*(.+)$')
                    if out then refScanNames(u8:decode(out), take) end
                end
                if line:find('Наименования купонов', 1, true) then
                    local rest = line:match(':%s*(.+)$') or ''
                    for item in rest:gmatch('%d+%)%s*([^;]+)') do
                        item = u8:decode(item):gsub('[%s%.;]+$', '')
                        take(item, u8:decode('купон '))
                    end
                end
            end
        end
        for _, e in pairs(MEM) do refScanNames(e.final, take) end
        for _, e in pairs(SRC) do refScanNames(e.text, take) end
        if added > 0 then
            namesSave()
            say(T('Справочник/память: добавлено названий в список: ') .. added)
        end
        local wf = io.open(flag, 'wb')
        if wf then wf:write(REF_SEED_VER); wf:close() end
    end)
end
