MULT = {}
for k, v in pairs({ [''] = 1, ['к'] = 1e3, ['кк'] = 1e6, ['ккк'] = 1e9, ['k'] = 1e3, ['kk'] = 1e6,
    ['тыс'] = 1e3 }) do MULT[T(k)] = v end

function parsePrice(num, suf)
    local mult = MULT[suf]
    if not mult then return nil end
    local v
    if mult > 1 then
        v = tonumber((num:gsub(',', '.')))
    else
        v = tonumber((num:gsub('[%.,]', '')))
    end
    if not v then return nil end
    return math.floor(v * mult + 0.5), mult
end

function money(v)
    local s = string.format('%d', v)
    local r = s:reverse():gsub('(%d%d%d)', '%1.')
    r = r:reverse()
    if r:sub(1, 1) == '.' then r = r:sub(2) end
    return cfg.dollarPrefix and ('$' .. r) or (r .. '$')
end
