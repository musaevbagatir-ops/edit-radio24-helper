local function esc(s) return (s:gsub('%%', '%%%%')) end

function drawFaq()
    imgui.TextWrapped(esc('Нажми на вопрос, чтобы открыть ответ.'))
    imgui.Separator()
    for _, sec in ipairs(FAQ) do
        imgui.TextColored(imgui.ImVec4(1, 0.67, 0.2, 1), esc(sec[1]))
        for _, qa in ipairs(sec[2]) do
            if imgui.CollapsingHeader(esc(qa[1]) .. '##faq' .. sec[1] .. qa[1]) then
                imgui.Indent()
                imgui.TextWrapped(esc(qa[2]))
                imgui.Unindent()
            end
        end
        imgui.Spacing()
    end
end
